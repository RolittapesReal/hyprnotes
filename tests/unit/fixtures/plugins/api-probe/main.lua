local function probe(name, f)
  local ok, err = pcall(f)
  hn.log(name .. "|" .. tostring(ok) .. "|" .. tostring(err))
end

hn.command{ id = "probe", title = "Probe", run = function()
  probe("note.text", function() return hn.note.text() end)
  probe("note.selection", function() return hn.note.selection() end)
  probe("note.path", function() return hn.note.path() end)
  probe("note.title", function() return hn.note.title() end)
  probe("note.tags", function() return hn.note.tags() end)
  probe("note.replace_selection", function() hn.note.replace_selection("x") end)
  probe("note.insert", function() hn.note.insert("x") end)
  probe("note.set_text", function() hn.note.set_text("x") end)
  probe("notes.list", function() return hn.notes.list("q") end)
  probe("notes.read", function() return hn.notes.read("a.md") end)
  probe("notes.create", function() return hn.notes.create("t", "body") end)
  probe("notes.write", function() return hn.notes.write("a.md", "body") end)
  probe("notes.delete", function() return hn.notes.delete("a.md") end)
  probe("ui.notify", function() return hn.ui.notify("hi") end)
  probe("ui.prompt", function() return hn.ui.prompt("t", "l", "d") end)
  probe("ui.confirm", function() return hn.ui.confirm("sure?") end)
  probe("ui.pick", function() return hn.ui.pick("t", {"a", "b"}) end)
  probe("storage.get", function() return hn.storage.get("k") end)
  probe("storage.set", function() hn.storage.set("k", {1, 2, 3}) end)
  probe("clipboard.get", function() return hn.clipboard.get() end)
  probe("clipboard.set", function() hn.clipboard.set("c") end)
  probe("http.get", function() return hn.http.get("https://api.example.com/x") end)
  probe("http.post", function() return hn.http.post("https://api.example.com/x", "{}") end)
  probe("theme.set_token", function() return hn.theme.set_token("accent", "#ff0000") end)
end }
