local function try(name, f)
  local ok, a, b = pcall(f)
  hn.log(name .. "|" .. tostring(ok) .. "|" .. tostring(a) .. "|" .. tostring(b))
end

hn.command{ id = "escape", title = "Escape", run = function()
  try("io", function() return io end)
  try("os", function() return os end)
  try("debug", function() return debug end)
  try("package", function() return package end)
  try("dofile", function() return dofile end)
  try("loadfile", function() return loadfile end)
  try("string.dump", function() return string.dump end)
  try("io.open", function() return io.open("/etc/passwd") end)
  try("os.execute", function() return os.execute("id") end)
  try("require ../", function() return require("../plugin") end)
  try("require /etc", function() return require("/etc/passwd") end)
  try("require os", function() return require("os") end)
  try("require io", function() return require("io") end)
  try("require missing", function() return require("nope") end)
  try("load io", function() return load("return io")() end)
  try("load file", function() return load("return 1", "=x", "t", {})() end)
  try("load bytecode", function() return load("\27Lua\84\0") end)
  try("load function", function() return load(function() return nil end) end)
  try("getmetatable string", function() return getmetatable("").__index == string end)
  try("gc stop", function() return collectgarbage("stop") end)
  try("gc setpause", function() return collectgarbage("setpause", 1000) end)
  try("gc count", function() return type(collectgarbage("count")) end)
  try("rawget io", function() return rawget(_G, "io") end)
  try("_G.io", function() return _G.io end)
  try("coroutine io", function() return coroutine.wrap(function() return io end)() end)
  try("string.rep bomb", function() return #string.rep("x", 1e10) end)
  try("string.rep ok", function() return #string.rep("ab", 1000, ",") end)
  try("warn", function() return warn end)
end }
